// The fixture PDFs and golden snapshots are committed. These checks keep them honest:
// `npm run fixtures` must reproduce the committed bytes, and every snapshot must have been taken
// from the fixture that is committed now (see tests/golden/README.md).
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, describe, expect, it } from "vitest";

const root = join(import.meta.dirname, "..", "..");
const fixtureDir = join(root, "tests", "fixtures");
const snapshotDir = join(root, "tests", "golden", "snapshots");
const examplePath = join(root, "public", "example-document.pdf");
const sha256 = (path: string) => createHash("sha256").update(readFileSync(path)).digest("hex");
const fixtures = readdirSync(fixtureDir).filter((f) => f.endsWith(".pdf"));
// Fixtures with no snapshot yet. statement.pdf's snapshot comes from the new engine, not the
// prototype (whose output for it is the bug of spec #22): #24 records it and removes it from here.
const awaitingSnapshot = new Set(["statement.pdf"]);

describe("fixture PDFs", () => {
  const out = mkdtempSync(join(tmpdir(), "table-lift-fixtures-"));
  afterAll(() => rmSync(out, { recursive: true, force: true }));

  it("are regenerated byte for byte by the fixture script", () => {
    execFileSync(process.execPath, [
      join(root, "scripts", "fixtures", "make-fixtures.mjs"),
      out,
      out,
    ]);
    const regenerated = readdirSync(out).filter((f) => f !== "example-document.pdf");
    expect(regenerated.sort()).toEqual(fixtures.sort());
    for (const f of fixtures) expect(sha256(join(out, f)), f).toBe(sha256(join(fixtureDir, f)));
    expect(sha256(join(out, "example-document.pdf"))).toBe(sha256(examplePath));
  }, 30_000);
});

describe("golden snapshots", () => {
  it("exist for every fixture and the Example Document", () => {
    const snapshots = readdirSync(snapshotDir).filter((f) => f.endsWith(".json"));
    const expected = ["example-document.pdf", ...fixtures]
      .filter((f) => !awaitingSnapshot.has(f))
      .map((f) => f.replace(/\.pdf$/, ".json"));
    expect(snapshots.sort()).toEqual(expected.sort());
  });

  it("were taken from the committed fixture bytes", () => {
    for (const f of readdirSync(snapshotDir).filter((s) => s.endsWith(".json"))) {
      const snap = JSON.parse(readFileSync(join(snapshotDir, f), "utf8"));
      expect(sha256(join(root, snap.fixture)), f).toBe(snap.sha256);
    }
  });
});
